-- Persistent inventory order. New products are appended automatically.
ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS display_order bigint GENERATED BY DEFAULT AS IDENTITY;

CREATE OR REPLACE VIEW public.current_stock
WITH (security_invoker = true) AS
SELECT p.id, p.name, p.spec, p.unit,
  coalesce(i.total_in, 0::numeric) AS total_inbound,
  coalesce(o.total_out, 0::numeric) AS total_outbound,
  coalesce(i.total_in, 0::numeric) - coalesce(o.total_out, 0::numeric) AS stock_qty,
  p.display_order
FROM public.products p
LEFT JOIN (
  SELECT product_id, sum(quantity) AS total_in
  FROM public.inbound_records GROUP BY product_id
) i ON p.id = i.product_id
LEFT JOIN (
  SELECT product_id, sum(quantity) AS total_out
  FROM public.outbound_records GROUP BY product_id
) o ON p.id = o.product_id
ORDER BY p.display_order, p.id;

-- Match the integer-only entry controls, including writes from older clients.
ALTER TABLE public.inbound_records
  ADD CONSTRAINT inbound_quantity_whole CHECK (quantity = trunc(quantity));
ALTER TABLE public.outbound_records
  ADD CONSTRAINT outbound_quantity_whole CHECK (quantity = trunc(quantity));
